--
-- Проект — копия системы, сделанной для другого клиента, и в базовых данных осталась
-- ЕГО ссылка (`proverka-zarabotka.online`). У Комарова свой оффер на домене `.ru`.
-- Настройка запасная (обычно ссылка берётся из активного промта, см. 0023), но пусть
-- запасное значение указывает на нужную воронку, а не на чужую.
--
-- Условие по старому значению обязательно: если клиент уже поменял ссылку в панели,
-- миграция не должна откатывать его правку при следующем деплое.

UPDATE settings
   SET value = 'https://proverka-zarabotka.ru',
       updated_at = now()
 WHERE key = 'ad_link'
   AND value = 'https://proverka-zarabotka.online';
