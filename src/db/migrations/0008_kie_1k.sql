-- экономия решающая. aspect_ratio при этом остаётся заданным явно: `auto` у kie.ai
-- принудительно даёт 1K, но тогда формат картинки непредсказуем.

UPDATE settings SET value = '1K', updated_at = now() WHERE key = 'kie_resolution';
