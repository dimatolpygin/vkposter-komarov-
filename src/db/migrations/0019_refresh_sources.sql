-- Обновление источников перед каждым прогоном.
--
-- Раньше прогон строил план из накопленного в базе, а сайты перечитывались только
-- при нехватке материалов. На проде это дало двое суток без единого обхода: запас
-- был, свежие статьи не забирались. Теперь обход идёт в начале прогона, а настройки
-- ниже позволяют его выключить и задать, как часто перечитывать один и тот же сайт.

INSERT INTO settings (key, value, title)
VALUES
  ('refresh_sources_enabled',        'on', 'Забирать свежее с сайтов перед каждым прогоном'),
  ('refresh_sources_min_age_minutes', '60', 'Не перечитывать источник чаще, чем раз в N минут')
ON CONFLICT (key) DO NOTHING;

-- Текстов за одну проверку было 10 при 50 обнаруженных материалах: остальные оседали
-- в базе без текста и в очередь не попадали никогда (у cryptorussia и kaper так
-- накопилось по 40 материалов). Тексты берутся через WP API, он бесплатный, поэтому
-- потолок поднимаем; firecrawl подключается только там, где WP API не отдал текст.
UPDATE settings
   SET value = '30', updated_at = now()
 WHERE key = 'extract_limit_per_check'
   AND value = '10';
