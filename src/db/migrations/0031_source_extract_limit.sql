-- Свой потолок извлечения текстов на источник.
--
-- Общая настройка `extract_limit_per_check` = 30 работала, пока платных источников было
-- мало и свежего у них выходило по несколько штук в день: фактический расход равнялся
-- числу новых материалов, а не потолку.
--
-- Три сайта из присланных клиентом ведут себя иначе. Замер карт 17.08.2026:
--   vsyapravda — 18 969 адресов, из них 13 096 попадают в окно свежести 30 дней;
--   backfund   — та же картина, плоская карта целиком «свежая»;
--   trustorg   — все 24 960 карточек сайтов помечены сегодняшним днём, сайт
--                перезаписывает их каждый день.
-- WP API у всех трёх закрыт (404), то есть каждый текст — это кредит firecrawl. При
-- потолке 30 они упираются в него каждую проверку: 90 кредитов в день, 2700 в месяц из
-- 5000 на весь проект, и это только они. Лимит уходил бы не на публикации, а на добор
-- бесконечной ленты справочников.
--
-- Поэтому потолок становится свойством источника. Бесплатным (wp_api) он не нужен вовсе:
-- у coinmania и torforex материал берётся запросом к их же API и ничего не стоит.

ALTER TABLE sources ADD COLUMN IF NOT EXISTS extract_limit integer;

COMMENT ON COLUMN sources.extract_limit IS
  'Сколько текстов извлекать за одну проверку этого источника. NULL — общая настройка extract_limit_per_check.';

-- Пять текстов за проверку на каждый — 15 кредитов в день, 450 в месяц. Материал они
-- отдают крупный (5-16 тысяч символов), пяти тем в день с одного сайта хватает с запасом:
-- дневная норма всего проекта — 44 темы, и большая часть закрывается бесплатными.
UPDATE sources
   SET extract_limit = 5,
       updated_at = now()
 WHERE code IN ('vsyapravda', 'backfund', 'trustorg');
