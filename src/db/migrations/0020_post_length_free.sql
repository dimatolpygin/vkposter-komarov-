-- Верхний предел длины поста снят по решению заказчика.
--
-- 2200 символов пришли из промта, а не из ограничений площадки: в записи ВК помещается
-- порядка 16 тысяч символов. На живых прогонах предел стоил переделок и отдельных
-- вызовов на сокращение, а иногда и потери темы: пост с правильной структурой и
-- рекламным блоком браковался за две сотни лишних символов.
--
-- Ноль в `post_max_chars` = ограничения нет, публикуем столько, сколько написала модель.
-- Нижний предел остаётся: он ловит обрубки, а не длину.

UPDATE settings
   SET value = '0', updated_at = now()
 WHERE key = 'post_max_chars'
   AND value = '2200';

UPDATE settings
   SET title = 'Максимальная длина поста, символов (0 - без ограничения)', updated_at = now()
 WHERE key = 'post_max_chars';

UPDATE settings
   SET title = 'Минимальная длина поста, символов (0 - без ограничения)', updated_at = now()
 WHERE key = 'post_min_chars';
