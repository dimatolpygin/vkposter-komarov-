-- Очередь источников: у кого темы берём раньше.
--
-- До этого очередь была одна на всех и строилась только по дате материала, поэтому
-- сайт, который публикует чаще соседей, занимал план целиком. Клиенту нужно, чтобы
-- cryptorussia бралась в последнюю очередь: её материалы идут в работу только тогда,
-- когда у остальных источников свежего не осталось.
--
-- Меньше число — раньше очередь. Значения из панели: 10 (первым), 100 (обычная),
-- 900 (последним) — числовое поле оставлено на случай более тонкой раскладки.

ALTER TABLE sources ADD COLUMN IF NOT EXISTS priority smallint NOT NULL DEFAULT 100;

UPDATE sources SET priority = 900, updated_at = now() WHERE code = 'cryptorussia';
