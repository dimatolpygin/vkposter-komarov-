-- Этап 9: развод двух разных «добров».
--
-- Ключ `backfill_enabled` занят с этапа 1 под совсем другое: это флаг «идёт разовое
-- наполнение из архива» (этап 10), и значение у него `true`/`false`. Настройка добора
-- старых тем внутри прогона — про другое и живёт под своим именем, иначе одно
-- переключалось бы вместе с другим.
INSERT INTO settings (key, value, title) VALUES
  ('topic_backfill_enabled', 'on', 'Добирать старые темы, когда свежих материалов меньше плана'),
  ('topic_backfill_max_days', '730', 'Насколько глубоко в архив уходит добор старых тем, дней')
ON CONFLICT (key) DO NOTHING;

-- Ключ, ошибочно заведённый миграцией 0013 под тем же смыслом.
DELETE FROM settings WHERE key = 'backfill_max_days';
