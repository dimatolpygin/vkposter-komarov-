-- capper-expert выключается по результату проверки на проде.
--
-- Локально сайт не открывался вовсе (fetch failed с машины разработчика), поэтому
-- вставлен он был включённым, с очередью 200 и пометкой «проверять на проде». Проверка
-- на проде прошла: сайт отвечает, карта читается, но обход даёт ноль адресов за одну
-- секунду — то есть дальше индекса дело не идёт.
--
-- Причина не в сайте и не в фильтре, а в датах: все его дочерние карты помечены
-- 01.07.2026, последняя запись в WP API — 25.06.2026, а окно свежести 30 дней отсекает
-- всё старше 18.07. Карты не проходят отбор ещё до чтения.
--
-- Это ровно тот же случай, что kapp1: источник живой, но по обычному обходу вечно
-- пустой. Держать такой включённым — значит показывать клиенту в панели строку
-- «проверен, найдено 0» и не иметь возможности отличить её от настоящей поломки.
-- Материал остаётся доступным через «Добор старых тем» с указанным периодом.
--
-- Если сайт снова начнёт публиковать, источник включается одной галочкой в панели.

UPDATE sources
   SET is_active = false,
       notes = 'ВЫКЛЮЧЕН: свежего нет. Проверка на проде 17.08.2026 — ноль адресов: '
               'карты помечены 01.07.2026, последняя запись 25.06.2026, окно свежести '
               '30 дней отсекает их на уровне индекса. WP API открыт, тексты бесплатны — '
               'включить, когда сайт снова начнёт публиковать. Архив берётся через '
               '«Добор старых тем» с периодом.',
       updated_at = now()
 WHERE code = 'capper-expert';
