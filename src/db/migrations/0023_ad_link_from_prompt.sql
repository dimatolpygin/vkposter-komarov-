-- Ссылка рекламного блока берётся из активного промта, а настройка стала запасной.
--
-- 11 августа клиент поменял в промте адрес сайта на приглашение в телеграм, а настройка
-- `ad_link` осталась прежней — валидация браковала каждый пост («нет рекламного блока
-- со ссылкой https://proverka-zarabotka.online»), хотя блок в тексте был. Правда о
-- ссылке одна и живёт там же, где сам блок. Значение настройки не трогаем: оно
-- используется, только если в промте ссылки нет вовсе.

UPDATE settings
   SET title = 'Ссылка в рекламном блоке (запасная: обычно берётся из промта)',
       updated_at = now()
 WHERE key = 'ad_link';
