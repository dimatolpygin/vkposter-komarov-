/**
 * Постобработка сгенерированного текста.
 *
 * Зачем кодом, а не промтом: просить модель «не используй markdown и длинное тире»
 * работает через раз, а чистка регулярками работает всегда. Промт отвечает за стиль,
 * код — за чистоту разметки.
 *
 * Что НЕЛЬЗЯ трогать (осознанный стиль клиента, а не мусор):
 *   - сами булиты в начале строки: так устроен формат поста в промте;
 *   - эмодзи-иконки 🔰 ❗️ ✅ — маркеры подзаголовков и рекламного блока;
 *   - разделители «--------» вокруг рекламного блока.
 *
 * Что делается с тире: внутри предложения оно убирается, а там, где остаётся
 * (булиты, рекламный блок), длинное «—» заменяется коротким «-». Длинных тире
 * в готовом тексте не остаётся вообще — требование заказчика.
 */

import { projectTokens, foldLatin } from './topic.js';

/** Строка-булит: тире (или дефис) с пробелом в начале строки. Сам булит сохраняем. */
const BULLET_LINE = /^(\s*)[—–-]\s+/;

/** Длинное и среднее тире. В готовом тексте их быть не должно — только дефис. */
const LONG_DASH = /[—–]/g;

/** Ряд дефисов — разделитель рекламного блока из промта, не markdown-hr. */
const AD_SEPARATOR = /^\s*-{4,}\s*$/;

function stripMarkdownInline(line) {
  return line
    // ссылки [текст](url) → «текст (url)»: ссылку из рекламного блока терять нельзя
    // Сравнение без хвостового слэша: модель часто пишет [https://site.ru](https://site.ru/),
    // и строгое равенство оставляло ссылку в тексте дважды.
    // Адрес берём любой, а не только http: модель пишет и «[здесь](vk.com/club1)»,
    // и «[тут](#itog)». Раньше такие ссылки чистка пропускала, а проверка их видела —
    // пост уходил в брак «осталась markdown-разметка» и возвращался в очередь каждый
    // день (материал «Mailbox Quarantine Alert» падал так трижды подряд).
    .replace(/\[([^\]]+)\]\(([^)\s]*)\)/g, (_, text, url) => {
      const bare = (value) => value.trim().replace(/\/+$/, '');
      // Якорь или пустой адрес — ведёт в никуда, оставляем только текст.
      if (!url || url.startsWith('#')) return text.trim();
      return bare(text) === bare(url) ? url.trim() : `${text} ${url}`;
    })
    // **жирный**, __жирный__, *курсив*, _курсив_
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/__([^_]+)__/g, '$1')
    .replace(/(^|[\s(«"])\*([^*\n]+)\*(?=[\s).,!?»"]|$)/g, '$1$2')
    .replace(/(^|[\s(«"])_([^_\n]+)_(?=[\s).,!?»"]|$)/g, '$1$2')
    // `код` и ~~зачёркнутый~~
    .replace(/`([^`]+)`/g, '$1')
    .replace(/~~([^~]+)~~/g, '$1')
    // Остатки звёздочек: пары выше снимаются только когда открывающая и закрывающая
    // стоят в одной строке. Модель регулярно выделяет заголовок «**Итог:» и закрывает
    // его строкой ниже (или не закрывает вовсе) — символы оставались в тексте, и пост
    // браковался за разметку, которой в готовом посте всё равно не место.
    .replace(/\*\*/g, '')
    // «https://site.ru (https://site.ru/)» → одна ссылка. Так выглядит уже разобранная
    // markdown-ссылка, у которой текст и адрес различались только слэшем.
    .replace(/(https?:\/\/[^\s()]+?)\/?\s+\((https?:\/\/[^\s()]+?)\/?\)/g, (match, first, second) =>
      first === second ? first : match);
}

/**
 * Тире внутри предложения заменяется на запятую или убирается.
 * «Проект — это развод» → «Проект это развод». Тире в начале строки (булит) сохраняется,
 * поэтому обработка идёт построчно и первый символ строки не участвует.
 */
function stripInlineDash(line) {
  const bullet = line.match(BULLET_LINE);
  // Булит сохраняем как маркер, но приводим к короткому дефису.
  const head = bullet ? `${bullet[1]}- ` : '';
  const rest = bullet ? line.slice(bullet[0].length) : line;
  const cleaned = rest
    // «слово — слово» → «слово слово»; двойной пробел подчищается ниже
    .replace(/\s+[—–]\s+/g, ' ')
    // «слово—слово» без пробелов
    .replace(/(\S)[—–](\S)/g, '$1 $2');
  return head + cleaned;
}

export function cleanPostText(raw) {
  if (!raw) return '';

  // Рекламный блок между строками-разделителями — дословный текст клиента.
  // Внутри него не чистим ничего, кроме markdown: там есть «— он принес нам…»,
  // и удаление этого тире ломает фразу заказчика.
  let insideAd = false;

  const lines = String(raw)
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => {
      if (AD_SEPARATOR.test(line)) {
        insideAd = !insideAd;
        return line.trim();
      }
      // В рекламном блоке текст клиента дословный: тире там не удаляем (иначе ломается
      // фраза «— он принес нам»), но длинное меняем на короткое.
      if (insideAd) return stripMarkdownInline(line).replace(LONG_DASH, '-').trimEnd();

      let out = line
        // заголовки markdown: решётки убираем, текст оставляем
        .replace(/^\s*#{1,6}\s+/, '')
        // цитаты
        .replace(/^\s{0,3}>\s?/, '')
        // нумерованные и звёздочные списки приводим к булиту клиента
        .replace(/^\s*\d+[.)]\s+/, '- ')
        .replace(/^\s*[*+]\s+/, '- ');

      out = stripMarkdownInline(out);
      out = stripInlineDash(out);

      return out.replace(/[ \t]{2,}/g, ' ').trimEnd();
    });

  return lines
    .join('\n')
    // больше двух пустых строк подряд не нужно
    .replace(/\n{3,}/g, '\n\n')
    // Контрольный проход: длинных тире в тексте не остаётся ни в каком виде.
    .replace(LONG_DASH, '-')
    .trim();
}

/**
 * Обрезка лишних пунктов в списках. Последняя мера против переросшего поста, когда
 * модель уже трижды отказалась уложиться в лимит.
 *
 * Почему именно пункты: промт клиента просит по три пункта в двух блоках, а модель
 * регулярно выдаёт по пять-шесть, и именно они дают перебор. Удаление лишних пунктов
 * с конца блока не ломает ни структуру, ни рекламный блок, ни «Итог» — в отличие от
 * обрезки текста по символам, которая оставляет пост оборванным на полуслове.
 *
 * @param {string} text
 * @param {number} keepPerBlock сколько пунктов оставить в каждом блоке
 */
export function trimBulletLists(text, keepPerBlock = 3) {
  const lines = String(text ?? '').split('\n');
  const out = [];
  let insideAd = false;
  let bulletsInBlock = 0;

  for (const line of lines) {
    if (AD_SEPARATOR.test(line)) {
      insideAd = !insideAd;
      bulletsInBlock = 0;
      out.push(line);
      continue;
    }
    // В рекламном блоке не трогаем ничего: это дословный текст клиента.
    if (!insideAd && /^\s*[—–-]\s+\S/.test(line)) {
      bulletsInBlock += 1;
      if (bulletsInBlock > keepPerBlock) continue;
    } else if (line.trim() === '') {
      bulletsInBlock = 0;
    }
    out.push(line);
  }

  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

/**
 * Проверка поста на соответствие требованиям промта. Возвращает список нарушений;
 * пустой список = пост годен. Генерация повторяется, пока список не опустеет.
 *
 * @param {string} text
 * @param {object} rules
 * @param {number} rules.minChars
 * @param {number} rules.maxChars
 * @param {string} rules.adLink   ссылка рекламного блока
 * @param {string} [rules.topicName] название проекта — должно быть в первом абзаце
 */
export function validatePost(text, { minChars, maxChars, adLink, topicName }) {
  const problems = [];
  const value = String(text ?? '');

  // Ноль в любом из пределов = ограничения нет. Верхний предел по умолчанию снят по
  // решению заказчика: у ВК в записи помещается порядка 16 тысяч символов, а лишние
  // двести символов у хорошего в остальном поста не повод его выбрасывать.
  if (minChars > 0 && value.length < minChars) {
    problems.push(`коротко: ${value.length} символов, нужно от ${minChars}`);
  }
  if (maxChars > 0 && value.length > maxChars) {
    problems.push(`длинно: ${value.length} символов, нужно до ${maxChars}`);
  }

  // «Первый абзац» — первые два блока до пустой строки. Два, а не один: заголовок
  // приходит отдельным полем схемы, но модель нередко дублирует его первой строкой тела,
  // и тогда зачин со словом «отзыв» оказывается во втором блоке. Проверка по одному
  // блоку отбраковывала нормальные посты (поймано на первом живом прогоне).
  const blocks = value.split(/\n\s*\n/).map((block) => block.trim()).filter(Boolean);
  const firstParagraph = blocks.slice(0, 2).join('\n').toLowerCase();

  if (!/отзыв/.test(firstParagraph)) {
    problems.push('в первом абзаце нет слова «отзыв»');
  }
  if (topicName && !mentionsProject(firstParagraph, topicName)) {
    problems.push(`в первом абзаце нет названия проекта («${topicName}»)`);
  }
  // Структура из промта клиента: два блока с булитами и блок «Итог». Проверяем кодом,
  // а не надеемся на модель: без булитов пост в ВК читается стеной текста.
  // Булит после чистки короткий, но принимаем и длинное тире: валидация вызывается
  // и на тексте до постобработки (в тестах и при разборе сбоев).
  const bulletLines = value.split('\n').filter((line) => /^\s*[—–-]\s+\S/.test(line)).length;
  if (bulletLines < 4) {
    problems.push(`мало пунктов-булитов: ${bulletLines}, нужно минимум 4 (по 2-3 в двух блоках)`);
  }
  // Заключительный блок. Заголовок у него зависит от промта клиента: у первого это
  // «Итог:», у второго — «💬Наш отзыв:». Поэтому принимаем оба и разрешаем перед
  // словом любые незначащие символы: эмодзи клиент ставит вплотную, без пробела,
  // и проверка на `^\s*наш отзыв` не сработала бы ни разу.
  //
  // Без \b: в JS границей слова считается только ASCII, и после кириллического «итог»
  // \b не срабатывает — проверка не находила даже строку «Итог:».
  if (!/^[^\p{L}\n]*(итог|наш отзыв)/imu.test(value)) {
    problems.push('нет заключительного блока («Итог» или «Наш отзыв»)');
  }

  if (adLink && !value.includes(adLink)) {
    problems.push(`нет рекламного блока со ссылкой ${adLink}`);
  }
  if (/\*\*|^#{1,6}\s|\[[^\]]+\]\(/m.test(value)) {
    problems.push('осталась markdown-разметка');
  }

  return problems;
}

/**
 * Название проекта в первом абзаце. Сравнение нежёсткое: модель пишет «PipNest Markets»,
 * «Пипнест» или «pipnest markets» — требовать точного совпадения строки бессмысленно.
 *
 * Совпадением считается ЛЮБОЕ значимое слово названия, а не самое длинное. Раньше
 * бралось самое длинное — и на живом прогоне это забраковало три подряд нормальных
 * поста: тема пришла slug'ом «xrp-turbo-io-razoblachenie», самым длинным словом
 * оказалось «razoblachenie», а в тексте, разумеется, было «XRP Turbo».
 * Жанровые слова и доменные зоны выброшены (см. projectTokens): по ним проверять
 * нечего. Если после чистки значимых слов не осталось — проверку не применяем:
 * брак поста из-за мусорного названия темы был бы наказанием не за то.
 */
/**
 * Основа слова: слово без двух последних букв, но не короче четырёх.
 *
 * Русские названия склоняются, а проверка искала точное вхождение. Тема «Ксения
 * Зюзгина» при совершенно нормальном тексте «Ксении Зюзгиной» проваливала проверку
 * три раза подряд, и пост уходил в брак — в журнале это выглядело ежедневной ошибкой.
 * Отсечение хвоста ловит любой падеж («зюзгин» есть и в «Зюзгиной», и в «Зюзгину»),
 * а порог в четыре символа держит ложные совпадения на приемлемом уровне: проверка
 * и так подтверждает лишь то, что название вообще упомянуто.
 */
function stem(word) {
  // Длинное название из адреса («playfortunage8d959») в тексте живёт коротким именем
  // («PlayFortune»): хвост из служебных символов дописан площадкой, а не проектом.
  if (word.length >= 8) return word.slice(0, 6);
  return word.length > 5 ? word.slice(0, word.length - 2) : word;
}

function mentionsProject(paragraph, topicName) {
  const haystack = paragraph.replace(/[^\p{L}\p{N}]+/gu, '').toLowerCase();
  const { words, folded } = projectTokens(topicName);
  if (words.length === 0) return true;

  const compact = words.join('').toLowerCase();
  if (compact.length >= 4 && haystack.includes(compact)) return true;

  // Транслит с обеих сторон: название латиницей, а пост кириллицей (и наоборот) —
  // обычное дело, «Atlas capital» против «Атлас Капитал».
  const haystackFolded = foldLatin(haystack);
  if (words.some((word, index) => {
    const value = word.toLowerCase();
    if (value.length >= 4 && haystack.includes(stem(value))) return true;
    const key = folded[index];
    return key.length >= 4 && haystackFolded.includes(stem(key));
  })) return true;

  // Короткие названия. Порог в четыре символа взят против ложных совпадений: обрывок
  // из двух букв найдётся в любом тексте. Но проект «CLW» — это всё название целиком,
  // и раньше проверка для него проваливалась всегда, каким бы ни был пост: на проде
  // это стоило трёх попыток генерации и потерянной темы. Ищем такое название как
  // отдельное слово, по границам, в исходном тексте, а не в сжатом.
  const short = words.filter((word) => word.length >= 2 && word.length < 4);
  if (short.length === 0) return false;
  const paragraphFolded = foldLatin(paragraph);
  return short.some((word) => {
    const value = word.toLowerCase();
    const asWord = new RegExp(`(?<![\\p{L}\\p{N}])${escapeRe(value)}(?![\\p{L}\\p{N}])`, 'u');
    return asWord.test(paragraph) || asWord.test(paragraphFolded);
  });
}

function escapeRe(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
